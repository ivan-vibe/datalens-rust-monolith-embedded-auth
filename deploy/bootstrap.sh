#!/usr/bin/env bash
# One-time secret material for the compose cluster: the self-signed TLS certificate, the PS256
# key pair shared by auth/monolith/ui, and the master tokens. Everything lands in
# deploy/secrets/ (gitignored) and deploy/certs/ (gitignored).
#
#   ./deploy/bootstrap.sh            # create what is missing
#   ./deploy/bootstrap.sh --force    # rotate every secret
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEPLOY="$ROOT/deploy"
SECRETS="$DEPLOY/secrets"
FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

"$DEPLOY/gen-cert.sh"
mkdir -p "$SECRETS"

if [ "$FORCE" = 1 ] || [ ! -s "$SECRETS/auth_private.pem" ]; then
  rm -f "$SECRETS/auth_private.pem" "$SECRETS/auth_public.pem"
  openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 \
    -out "$SECRETS/auth_private.pem" 2>/dev/null
  openssl pkey -in "$SECRETS/auth_private.pem" -pubout \
    -out "$SECRETS/auth_public.pem" 2>/dev/null
  chmod 600 "$SECRETS/auth_private.pem"
  echo "generated PS256 key pair in deploy/secrets/"
fi

if [ "$FORCE" = 1 ] || [ ! -s "$SECRETS/compose.secrets.yml" ]; then
  AUTH_MASTER_TOKEN="auth-$(openssl rand -hex 16)"
  US_MASTER_TOKEN="us-$(openssl rand -hex 16)"
  python3 - "$SECRETS/auth_private.pem" "$SECRETS/auth_public.pem" \
    "$AUTH_MASTER_TOKEN" "$US_MASTER_TOKEN" "$SECRETS/compose.secrets.yml" <<'PY'
import sys

private_key = open(sys.argv[1]).read()
public_key = open(sys.argv[2]).read()
auth_token, us_token = sys.argv[3], sys.argv[4]


def yaml_string(value: str) -> str:
    # YAML double-quoted scalars turn `\n` into a real newline; PEM env vars need that.
    escaped = value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
    return f'"{escaped}"'


with open(sys.argv[5], 'w') as handle:
    handle.write("# Generated by deploy/bootstrap.sh — never commit this file.\nservices:\n")
    handle.write("  monolith:\n    environment:\n")
    handle.write(f"      TOKEN_PRIVATE_KEY: {yaml_string(private_key)}\n")
    handle.write(f"      TOKEN_PUBLIC_KEY: {yaml_string(public_key)}\n")
    handle.write(f"      MASTER_TOKEN: {yaml_string(auth_token)}\n")
    handle.write(f"      AUTH__JWT_KEY: {yaml_string(public_key)}\n")
    handle.write(f"      AUTH_TOKEN_PUBLIC_KEY: {yaml_string(public_key)}\n")
    handle.write(f"      AUTH_MASTER_TOKEN: {yaml_string(auth_token)}\n")
    handle.write(f"      US_MASTER_TOKEN: {yaml_string(us_token)}\n")
    handle.write(f"      MASTER_TOKEN_US: {yaml_string(us_token)}\n")
    handle.write("  ui:\n    environment:\n")
    handle.write(f"      AUTH_TOKEN_PUBLIC_KEY: {yaml_string(public_key)}\n")
    handle.write(f"      AUTH_MASTER_TOKEN: {yaml_string(auth_token)}\n")
    handle.write(f"      US_MASTER_TOKEN: {yaml_string(us_token)}\n")
PY
  chmod 600 "$SECRETS/compose.secrets.yml"
  echo "wrote deploy/secrets/compose.secrets.yml"
fi

echo "bootstrap ok: deploy/certs + deploy/secrets ready"
