//! `encodeId`/`decodeId` — the 13-char id codec shared by US and auth.
//!
//! Ported from the TypeScript `Utils.encodeId`/`decodeId` (via `vendor/us-rust/src/id.rs`,
//! which is the same algorithm): base-36 alphabet rotated by `(id % 100) % 36`, with the
//! rotation index appended as the last character. Auth stores `BIGINT` ids but puts the
//! *encoded* form into JWT claims and API responses; control-api/US decode the same way.

const CODING_BASE: &[u8; 36] = b"0123456789abcdefghijklmnopqrstuvwxyz";
const RADIX: u64 = 36;
const ENCODED_ID_LENGTH: usize = 13;

fn rotation_number(id: i64) -> usize {
    (id.unsigned_abs() % 100) as usize % CODING_BASE.len()
}

fn rotated_base(rotation: usize) -> [u8; CODING_BASE.len()] {
    let mut base = [0u8; CODING_BASE.len()];
    for (index, slot) in base.iter_mut().enumerate() {
        *slot = CODING_BASE[(index + rotation) % CODING_BASE.len()];
    }
    base
}

/// `encodeId`: the zero id encodes to an empty string, exactly like the TypeScript original.
pub fn encode_id(id: i64) -> String {
    if id == 0 {
        return String::new();
    }

    let rotation = rotation_number(id);
    let base = rotated_base(rotation);

    let mut value = id.unsigned_abs();
    let mut digits = [0u8; 16];
    let mut cursor = digits.len();
    while value > 0 {
        cursor -= 1;
        digits[cursor] = base[(value % RADIX) as usize];
        value /= RADIX;
    }

    let mut encoded = String::with_capacity(digits.len() - cursor + 1);
    for digit in &digits[cursor..] {
        encoded.push(*digit as char);
    }
    encoded.push(CODING_BASE[rotation] as char);
    encoded
}

/// Errors the lenient (API-parameter) decoder can produce, mirroring Node `decodeId`:
/// invalid characters throw, values above the signed 64-bit range reach PostgreSQL and
/// become the `AUTH.DB.NUMERIC_VALUE_OUT_OF_RANGE` error there.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LenientIdError {
    InvalidChar,
    Overflow,
}

/// Node `decodeId`: no length or rotation re-check (the reference API accepts any base-36
/// string whose last character is a valid rotation index). Used for path/body id parameters,
/// not for JWT claims.
pub fn decode_id_lenient(input: &str) -> Result<i64, LenientIdError> {
    let bytes = input.as_bytes();
    let (suffix, long_part) = bytes.split_last().ok_or(LenientIdError::InvalidChar)?;
    let rotation = CODING_BASE
        .iter()
        .position(|candidate| candidate == suffix)
        .ok_or(LenientIdError::InvalidChar)?;
    let base = rotated_base(rotation);
    let mut value: u64 = 0;
    for byte in long_part {
        let digit = base
            .iter()
            .position(|candidate| candidate == byte)
            .ok_or(LenientIdError::InvalidChar)? as u64;
        value = value
            .checked_mul(RADIX)
            .and_then(|value| value.checked_add(digit))
            .ok_or(LenientIdError::Overflow)?;
    }
    i64::try_from(value).map_err(|_| LenientIdError::Overflow)
}

/// `encodeId` applied to an id decoded from user input. The Node function receives the
/// decimal string from `decodeId`, so a decoded zero is the string `"0"` (truthy) and
/// encodes to `"00"`, not to the empty string a numeric zero would produce.
pub fn encode_id_for_message(id: i64) -> String {
    if id == 0 {
        "00".to_string()
    } else {
        encode_id(id)
    }
}

/// `decodeId`: strict about length and the rotation suffix, but also re-checks the rotation
/// so a tampered suffix is rejected instead of silently decoding a different id.
pub fn decode_id(input: &str) -> Option<i64> {
    let bytes = input.as_bytes();
    if bytes.len() != ENCODED_ID_LENGTH {
        return None;
    }
    let (suffix, long_part) = bytes.split_last()?;
    let rotation = CODING_BASE
        .iter()
        .position(|candidate| candidate == suffix)?;
    let base = rotated_base(rotation);

    let mut value: u64 = 0;
    for byte in long_part {
        let digit = base.iter().position(|candidate| candidate == byte)? as u64;
        value = value.checked_mul(RADIX)?.checked_add(digit)?;
    }
    let value = i64::try_from(value).ok()?;
    if rotation_number(value) != rotation {
        return None;
    }
    Some(value)
}

#[cfg(test)]
mod tests {
    use super::*;

    // Vectors generated by the original TypeScript implementation (`power-radix` +
    // `Utils.encodeId`) — the same list `vendor/us-rust/src/id.rs` tests.
    const ROUND_TRIP: &[(i64, &str)] = &[
        (1_844_674_407_370_955_161, "3p837si3kczqp"),
        (2_099_999_999_999_999_999, "6p46m4jdid42r"),
        (2_100_000_000_000_000_000, "fydfvdsmrmdc0"),
        (2_200_000_000_000_000_123, "3cdpji82xpl6n"),
        (4_123_456_789_012_345_678, "1hzdlz2ksrgs6"),
        (999_999_999_999_999_999, "yc955oqovboir"),
        (4_611_686_018_427_387_903, "24flccmma7a63"),
        (1_234_567_890_123_456_789, "qu5i90kqn4wqh"),
    ];

    #[test]
    fn encode_and_decode_match_typescript() {
        for (id, expected) in ROUND_TRIP {
            assert_eq!(encode_id(*id), *expected, "encode_id({id})");
            assert_eq!(decode_id(expected), Some(*id), "decode_id({expected})");
        }
    }

    #[test]
    fn lenient_decoder_matches_node() {
        // Vectors observed from the Node implementation:
        // `decodeId('123') === '1259'`, `decodeId('abc') === '1259'`, `decodeId('zz') === '0'`,
        // `decodeId('12$')` throws.
        assert_eq!(decode_id_lenient("123"), Ok(1259));
        assert_eq!(decode_id_lenient("abc"), Ok(1259));
        assert_eq!(decode_id_lenient("zz"), Ok(0));
        assert_eq!(decode_id_lenient("12$"), Err(LenientIdError::InvalidChar));
        assert_eq!(decode_id_lenient(""), Err(LenientIdError::InvalidChar));
        // A canonical encoded id decodes to the same value as the strict decoder.
        assert_eq!(decode_id_lenient("3p837si3kczqp"), Ok(1_844_674_407_370_955_161));
        assert_eq!(encode_id_for_message(0), "00");
        assert_eq!(encode_id_for_message(1_844_674_407_370_955_161), "3p837si3kczqp");
    }

    #[test]
    fn decode_rejects_bad_input() {
        assert_eq!(decode_id(""), None);
        assert_eq!(decode_id("3p837si3kczq"), None);
        // Suffix changed: the rotation re-check must reject it.
        assert_eq!(decode_id("3p837si3kczq0"), None);
        assert_eq!(decode_id("3p837si3kcz$q"), None);
    }
}
